#include "pch.h"
#include "AssetManifest.h"
#include "Platform.h"
#include <fstream>
#include <filesystem>

namespace Demo {
	std::vector<std::wstring> ReadAssetManifest(const std::string& file) {
		std::vector<std::wstring> paths;
		std::ifstream in(file);
		std::string line;
		while (std::getline(in, line)) {
			while (!line.empty() && (line.back() == '\r' || line.back() == ' ')) line.pop_back();
			if (line.empty() || line[0] == '#') continue;
			paths.push_back(sdlgf::Platform::Utf8ToWide(line));
		}
		return paths;
	}

	bool WriteAssetManifest(const std::string& file, const std::vector<std::wstring>& paths) {
		std::error_code ec;
		std::filesystem::create_directories(std::filesystem::path(file).parent_path(), ec);
		std::ofstream out(file, std::ios::trunc);
		if (!out) return false;
		out << "# Textures the world scenes ask for. Generated by `demo --record-assets <file>`; do not edit by hand.\n";
		for (const auto& path : paths) out << sdlgf::Platform::WideToUtf8(path) << "\n";
		return out.good();
	}
}
